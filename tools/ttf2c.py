#!/usr/bin/env python3
"""Rasterize a TTF/OTF into an anti-aliased (8-bit alpha) glyph atlas in C.

Usage:
  python3 -I tools/ttf2c.py <font.ttf> <pixel-size> <c-symbol> > kernel/gfx/afont_<name>.c

Requires Pillow (FreeType). Covers printable ASCII 0x20-0x7e plus extra slots
0x7f = U+00B7 MIDDLE DOT, 0x80 = U+00B0 DEGREE SIGN, 0x81 = U+2022 BULLET,
0x82 = U+2014 EM DASH, 0x83 euro, 0x84 en dash, 0x85 ellipsis, 0x86/0x87 single
and 0x88/0x89 double curly quotes, 0x8a trade mark; 0x8b..0x9f are empty; 0xA0..0xFF
are U+00A0..U+00FF. A mild gamma (0.85) thickens stems slightly so small
text stays legible when alpha-blended in linear space.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

# Slots 0xA0..0xFF map 1:1 to U+00A0..U+00FF (Latin-1 Supplement).
EXTRA = {0x7f: 0x00B7, 0x80: 0x00B0, 0x81: 0x2022, 0x82: 0x2014,
         0x83: 0x20AC, 0x84: 0x2013, 0x85: 0x2026, 0x86: 0x2018,
         0x87: 0x2019, 0x88: 0x201C, 0x89: 0x201D, 0x8a: 0x2122}
FIRST, LAST = 0x20, 0xFF
GAMMA = 0.85


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, size, sym = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    lut = [round(255 * (v / 255) ** GAMMA) for v in range(256)]
    glyphs, data = [], []
    for code in range(FIRST, LAST + 1):
        if 0x8b <= code <= 0x9f:
            glyphs.append((len(data), 0, 0, 0, 0, 0))
            continue
        ch = chr(EXTRA.get(code, code))
        adv = round(font.getlength(ch))
        pad = size
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop(bbox)
        w, h = crop.size
        off = len(data)
        data.extend(lut[v] for v in crop.getdata())
        # bx: left bearing from pen x; by: top row relative to the line top
        glyphs.append((off, w, h, x0 - pad, y0 - pad, adv))

    name = path.split("/")[-1]
    out = ["// Generated by tools/ttf2c.py from %s at %d px -- do not edit." % (name, size),
           "// Inter font, Copyright (c) 2016 The Inter Project Authors, SIL OFL 1.1.",
           "// See assets/fonts/LICENSE.inter.",
           '#include "font.h"', "",
           "static const uint8_t %s_data[%d] = {" % (sym, len(data))]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append("")
    out.append("static const struct aglyph %s_glyphs[%d] = {" % (sym, LAST - FIRST + 1))
    for code, g in zip(range(FIRST, LAST + 1), glyphs):
        out.append("    { %d, %d, %d, %d, %d, %d },  // 0x%02x" % (g + (code,)))
    out.append("};")
    out.append("")
    out.append("const struct afont %s = { %d, %d, 0x%02x, 0x%02x, %s_glyphs, %s_data };"
               % (sym, ascent + descent, ascent, FIRST, LAST, sym, sym))
    print("\n".join(out))


if __name__ == "__main__":
    main()
