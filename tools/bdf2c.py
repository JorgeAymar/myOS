#!/usr/bin/env python3
"""Convert a fixed-cell BDF bitmap font into a C array for the myOS kernel.

Usage:  python3 -I tools/bdf2c.py <font.bdf> <c-symbol> > kernel/gfx/font_<name>.c

Emits printable ASCII (0x20-0x7e) plus three extra slots used by the UI:
  0x7f = U+00B7 MIDDLE DOT, 0x80 = U+00B0 DEGREE SIGN, 0x81 = U+2022 BULLET.
Every glyph row is a uint16_t, left-aligned (bit 15 = leftmost pixel).
Glyphs are placed in a full W x H cell using the BDF bounding boxes, so fonts
with per-glyph BBX values also convert correctly.
"""
import sys

EXTRA = {0x7f: 0x00B7, 0x80: 0x00B0, 0x81: 0x2022}
FIRST, LAST = 0x20, 0x81


def parse(path):
    glyphs, props = {}, {}
    with open(path, encoding="latin-1") as f:
        lines = [l.rstrip("\n") for l in f]
    i = 0
    while i < len(lines):
        parts = lines[i].split()
        if not parts:
            i += 1
            continue
        key = parts[0]
        if key == "FONTBOUNDINGBOX":
            props["fbb"] = tuple(int(v) for v in parts[1:5])
        elif key == "FONT_ASCENT":
            props["ascent"] = int(parts[1])
        elif key == "STARTCHAR":
            enc, bbx, rows = None, None, []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                p = lines[i].split()
                if p and p[0] == "ENCODING":
                    enc = int(p[1])
                elif p and p[0] == "BBX":
                    bbx = tuple(int(v) for v in p[1:5])
                elif p and p[0] == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    break
                i += 1
            if enc is not None and bbx is not None:
                glyphs[enc] = (bbx, rows)
        i += 1
    return props, glyphs


def render(props, glyph):
    fw, fh, fx, fy = props["fbb"]
    (bw, bh, bx, by), rows = glyph
    cell = [0] * fh
    # BDF: y offsets are relative to the baseline; the cell top is at fh+fy.
    top = fh + fy - (bh + by)
    for r, hexrow in enumerate(rows):
        bits = int(hexrow, 16)
        nbits = len(hexrow) * 4
        y = top + r
        if not 0 <= y < fh:
            continue
        for x in range(bw):
            if bits & (1 << (nbits - 1 - x)):
                cx = x + bx - fx
                if 0 <= cx < 16:
                    cell[y] |= 1 << (15 - cx)
    return cell


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, sym = sys.argv[1], sys.argv[2]
    props, glyphs = parse(path)
    fw, fh = props["fbb"][0], props["fbb"][1]
    if fw > 16:
        sys.exit("fonts wider than 16 px are not supported")
    out = ["// Generated by tools/bdf2c.py from %s -- do not edit." % path.split("/")[-1],
           "// Spleen font, Copyright (c) 2018-2024 Frederic Cambus, BSD-2-Clause.",
           "// See assets/fonts/LICENSE.spleen.",
           '#include "font.h"', "",
           "static const uint16_t %s_rows[%d] = {" % (sym, (LAST - FIRST + 1) * fh)]
    for code in range(FIRST, LAST + 1):
        uni = EXTRA.get(code, code)
        g = glyphs.get(uni) or glyphs.get(0x3f)
        cell = render(props, g)
        label = chr(uni) if 0x20 < uni < 0x7f and uni != 0x5c else "U+%04X" % uni
        out.append("    // 0x%02x %s" % (code, label))
        for j in range(0, fh, 8):
            out.append("    " + ", ".join("0x%04x" % v for v in cell[j:j + 8]) + ",")
    out.append("};")
    out.append("")
    out.append("const struct font %s = { %d, %d, 0x%02x, 0x%02x, %s_rows };"
               % (sym, fw, fh, FIRST, LAST, sym))
    print("\n".join(out))


if __name__ == "__main__":
    main()
